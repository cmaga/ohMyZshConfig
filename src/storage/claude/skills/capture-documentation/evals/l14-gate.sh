#!/usr/bin/env bash
# l14-gate.sh: manual smoke test that a path-scoped rule stub under
# .claude/rules/vault/ loads on Read of a matching file, in the main session
# and inside a worker-agent subagent. Not run by run.sh (needs the claude CLI
# and a model round trip). Usage: bash l14-gate.sh [WORKDIR]
set -u
export LC_ALL=C
WORK=${1:-$(mktemp -d)}
REPO="$WORK/l14"
LOG="$REPO/.l14-log.jsonl"
rm -rf "$REPO"; mkdir -p "$REPO/src" "$REPO/.claude/rules/vault" "$REPO/docs/project-knowledge/components"
cd "$REPO" || exit 2
git init -q -b main
printf 'export function run() { return 1; }\n' > src/x.ts
printf -- '---\ntype: component\nstatus: active\ncreated: 2026-09-01\n---\n# X\n\nOwns run.\n\n## Reusable surface\n\n- `run` — `src/x.ts` — entry point\n' > docs/project-knowledge/components/x.md
cat > .claude/rules/vault/components-x.md <<'EOF'
---
paths: [src/x.ts]
---
<!-- generated by gen-vault-rules.sh from docs/project-knowledge/components/x.md; do not edit -->
Before editing these files, run `grep -n '^## Reusable surface' docs/project-knowledge/components/x.md` and read that section only; this component note owns these files.
EOF
cat > "$WORK/l14-settings.json" <<EOF
{"hooks": {"InstructionsLoaded": [{"hooks": [{"type": "command", "command": "jq -c . >> \"$LOG\""}]}]}}
EOF
git add -A && git commit -qm 'l14 gate fixture'
: > "$LOG"

echo "claude $(claude --version 2>/dev/null | head -n1)"
run() {
  local label=$1 prompt=$2 before after result
  before=$(grep -c 'components-x.md' "$LOG" 2>/dev/null); before=${before:-0}
  result=$(CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS=1500000 claude -p "$prompt" --settings "$WORK/l14-settings.json" --dangerously-skip-permissions --output-format json 2>"$WORK/l14-$label.err" | jq -r '.result // empty')
  after=$(grep -c 'components-x.md' "$LOG" 2>/dev/null); after=${after:-0}
  printf '%s: log hits %s -> %s\n' "$label" "$before" "$after"
  printf '%s: result: %s\n' "$label" "$(printf '%s' "$result" | head -c 400 | tr '\n' ' ')"
  if [ "$after" -gt "$before" ] && printf '%s' "$result" | grep -qF 'Before editing these files'; then
    echo "$label: PASS"
  else
    echo "$label: FAIL"
  fi
}
run main "Read src/x.ts and reply with the exact first sentence of any project rule that loaded for it. If none loaded, reply NONE."
run subagent "Use the worker-agent subagent to read src/x.ts and report back the exact first sentence of any project rule that loaded for it (reply NONE if none). Relay its answer verbatim."
echo "log: $LOG"
